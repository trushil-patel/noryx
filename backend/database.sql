create extension if not exists vector;

create table if not exists public.knowledge_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  original_url text not null,
  platform text not null,
  title text not null,
  summary text,
  key_takeaways jsonb,
  why_it_matters text,
  status text not null default 'processing',
  source_type text not null default 'link',
  embedding vector(3072),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.knowledge_tags (
  id bigint generated by default as identity primary key,
  knowledge_item_id uuid not null references public.knowledge_items(id) on delete cascade,
  tag text not null,
  unique (knowledge_item_id, tag)
);

alter table public.knowledge_items enable row level security;
alter table public.knowledge_tags enable row level security;

create policy "Users read own knowledge" on public.knowledge_items for select using (auth.uid() = user_id);
create policy "Users read own tags" on public.knowledge_tags for select using (exists (select 1 from public.knowledge_items k where k.id = knowledge_item_id and k.user_id = auth.uid()));

create index if not exists knowledge_items_user_created_idx on public.knowledge_items (user_id, created_at desc);
create index if not exists knowledge_items_embedding_idx on public.knowledge_items using hnsw (embedding vector_cosine_ops);

create table if not exists public.collections (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 80),
  description text check (description is null or char_length(description) <= 500),
  visibility text not null default 'private' check (visibility in ('private', 'friends')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.collection_items (
  collection_id uuid not null references public.collections(id) on delete cascade,
  knowledge_item_id uuid not null references public.knowledge_items(id) on delete cascade,
  added_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (collection_id, knowledge_item_id)
);

alter table public.collections enable row level security;
alter table public.collection_items enable row level security;

create policy "Users manage own collections" on public.collections
for all using (auth.uid() = owner_id) with check (auth.uid() = owner_id);

create policy "Users read items in own collections" on public.collection_items
for select using (
  exists (
    select 1 from public.collections c
    where c.id = collection_id and c.owner_id = auth.uid()
  )
);

create policy "Users add items to own collections" on public.collection_items
for insert with check (
  auth.uid() = added_by
  and exists (
    select 1 from public.collections c
    where c.id = collection_id and c.owner_id = auth.uid()
  )
  and exists (
    select 1 from public.knowledge_items k
    where k.id = knowledge_item_id and k.user_id = auth.uid()
  )
);

create policy "Users remove items from own collections" on public.collection_items
for delete using (
  exists (
    select 1 from public.collections c
    where c.id = collection_id and c.owner_id = auth.uid()
  )
);

create index if not exists collections_owner_updated_idx
on public.collections (owner_id, updated_at desc);

create index if not exists collection_items_knowledge_idx
on public.collection_items (knowledge_item_id);

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[a-z0-9_]{3,40}$'),
  display_name text not null check (char_length(trim(display_name)) between 1 and 80),
  avatar_url text,
  bio text check (bio is null or char_length(bio) <= 280),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.connections (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references public.profiles(user_id) on delete cascade,
  addressee_id uuid not null references public.profiles(user_id) on delete cascade,
  pair_key text generated always as (
    least(requester_id::text, addressee_id::text) || ':' ||
    greatest(requester_id::text, addressee_id::text)
  ) stored unique,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (requester_id <> addressee_id)
);

create table if not exists public.collection_members (
  collection_id uuid not null references public.collections(id) on delete cascade,
  connection_id uuid not null references public.connections(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  added_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (collection_id, user_id)
);

alter table public.profiles enable row level security;
alter table public.connections enable row level security;
alter table public.collection_members enable row level security;

create or replace function public.is_collection_owner(p_collection_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.collections c
    where c.id = p_collection_id and c.owner_id = auth.uid()
  );
$$;

create or replace function public.is_collection_member(p_collection_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.collection_members cm
    where cm.collection_id = p_collection_id and cm.user_id = auth.uid()
  );
$$;

revoke all on function public.is_collection_owner(uuid) from public;
revoke all on function public.is_collection_member(uuid) from public;
grant execute on function public.is_collection_owner(uuid) to authenticated, service_role;
grant execute on function public.is_collection_member(uuid) to authenticated, service_role;

create policy "Authenticated users discover profiles" on public.profiles
for select to authenticated using (true);

create policy "Users update own profile" on public.profiles
for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "Users read own connections" on public.connections
for select using (auth.uid() = requester_id or auth.uid() = addressee_id);

create policy "Users send connection requests" on public.connections
for insert with check (auth.uid() = requester_id and status = 'pending');

-- Connection updates are performed by the authenticated backend after it verifies
-- that the caller is the addressee. Direct PostgREST updates are intentionally denied.
revoke update on public.connections from anon, authenticated;

create policy "Participants remove connections" on public.connections
for delete using (auth.uid() = requester_id or auth.uid() = addressee_id);

create policy "Collection owners manage members" on public.collection_members
for all using (public.is_collection_owner(collection_members.collection_id))
with check (
  auth.uid() = added_by
  and public.is_collection_owner(collection_members.collection_id)
  and exists (
    select 1 from public.connections cn
    where cn.id = collection_members.connection_id
      and cn.status = 'accepted'
      and (
        (cn.requester_id = auth.uid() and cn.addressee_id = collection_members.user_id)
        or (cn.addressee_id = auth.uid() and cn.requester_id = collection_members.user_id)
      )
  )
);

create policy "Members read own collection membership" on public.collection_members
for select using (auth.uid() = user_id);

create policy "Members read shared collections" on public.collections
for select using (public.is_collection_member(collections.id));

create policy "Members read shared collection items" on public.collection_items
for select using (public.is_collection_member(collection_items.collection_id));

create policy "Members read shared knowledge" on public.knowledge_items
for select using (
  exists (
    select 1
    from public.collection_items ci
    where ci.knowledge_item_id = knowledge_items.id
      and public.is_collection_member(ci.collection_id)
  )
);

create policy "Members read shared knowledge tags" on public.knowledge_tags
for select using (
  exists (
    select 1
    from public.collection_items ci
    where ci.knowledge_item_id = knowledge_tags.knowledge_item_id
      and public.is_collection_member(ci.collection_id)
  )
);

create index if not exists profiles_username_idx on public.profiles (username);
create index if not exists connections_requester_idx on public.connections (requester_id, status);
create index if not exists connections_addressee_idx on public.connections (addressee_id, status);
create index if not exists collection_members_user_idx
on public.collection_members (user_id, created_at desc);

